"""Write src/components/Road.astro: the road on the front ridge (canvas Round 18, draft 2 "soft band").

A slightly darker band along the trail curve that narrows with distance, with a faint paper-coloured
centre dash; no outlines. Clipped to the front ridge's own outline, so the far end disappears exactly
over the crest at any window size. Usage: python3 -I road.py <out .astro>"""
import math
import sys

# same curve as the old dotted trail and the motorcycle's path (figgen.TRAIL)
TRAIL = [((-20, 746), (160, 706), (300, 736), (420, 706)), ((420, 706), (520, 682), (470, 660), (580, 654))]
# Wide windows show the scene past x = 0: a straight lead-in carries the road on from the trail's start,
# along its starting direction, until it has left the bottom of the scene (the trail itself stays as is).
LEAD = (-400, 830)
TRAIL_D = f'M{LEAD[0]} {LEAD[1]} L-20 746 C160 706 300 736 420 706 C520 682 470 660 580 654'
# front ridge outline, identical to .ridge-front in MountainScene.astro (keep in sync)
RIDGE_FRONT = ('M-1100 690 C-960 670 -820 700 -680 705 C-540 710 -380 680 -300 690 C-220 700 -120 730 0 700 '
               'C200 650 380 690 560 660 C760 628 900 690 1100 650 C1240 624 1360 660 1440 640 '
               'C1520 620 1600 610 1700 625 C1800 640 1880 660 2000 650 C2120 640 2200 615 2320 625 '
               'C2420 633 2480 645 2540 640 L2540 810 L-1100 810 Z')
NEAR, FAR = 12.0, 4.0           # road width at the left edge and at the crest (scene units)
FADE = (500, 576)               # x range over which the road fades out before the crest


def f(v):
    return f'{v:.1f}'.rstrip('0').rstrip('.')


def bez(seg, t):
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = seg
    u = 1 - t
    return (u ** 3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3,
            u ** 3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3)


def band(n=200):
    trail = [bez(s, i / (n // 2)) for s in TRAIL for i in range(n // 2)] + [TRAIL[-1][3]]
    x0, y0 = TRAIL[0][0]
    lead = [(LEAD[0] + (x0 - LEAD[0]) * k / 20, LEAD[1] + (y0 - LEAD[1]) * k / 20) for k in range(20)]
    pts = lead + trail
    acc = [0.0]
    for a, b in zip(trail, trail[1:]):
        acc.append(acc[-1] + math.dist(a, b))
    acc = [0.0] * len(lead) + acc  # full width along the lead-in, narrowing only along the trail
    left, right = [], []
    for i, p in enumerate(pts):
        q, r = pts[min(i + 1, len(pts) - 1)], pts[max(i - 1, 0)]
        dx, dy = q[0] - r[0], q[1] - r[1]
        L = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / L, dx / L
        w = (NEAR + (FAR - NEAR) * acc[i] / acc[-1]) / 2
        left.append((p[0] + nx * w, p[1] + ny * w))
        right.append((p[0] - nx * w, p[1] - ny * w))
    ring = left + list(reversed(right))
    return 'M' + ' L'.join(f'{f(x)} {f(y)}' for x, y in ring) + ' Z'


astro = f'''---
// Road on the front ridge (Round 18, draft 2: soft band). Generated by scripts/road.py; edit the
// script, not this file. Lives inside MountainScene's <svg> (1440x810 scene units). Clipped to the
// front ridge so the far end disappears over the crest; the band is blurred a little like the ridges.
---

<defs>
  <clipPath id="road-clip"><path d="{RIDGE_FRONT}"></path></clipPath>
  <filter id="road-soft" x="-2%" y="-20%" width="104%" height="140%">
    <feGaussianBlur stdDeviation="0.7"></feGaussianBlur>
  </filter>
  <!-- the last stretch runs almost along the crest: fade it out there instead of hugging the edge -->
  <linearGradient id="road-fade-grad" gradientUnits="userSpaceOnUse" x1="{FADE[0]}" y1="0" x2="{FADE[1]}" y2="0">
    <stop offset="0" stop-color="#fff"></stop>
    <stop offset="1" stop-color="#000"></stop>
  </linearGradient>
  <mask id="road-fade" maskUnits="userSpaceOnUse" x="-1100" y="600" width="1760" height="300">
    <rect x="-1100" y="600" width="1760" height="300" fill="url(#road-fade-grad)"></rect>
  </mask>
</defs>
<g class="road" clip-path="url(#road-clip)" mask="url(#road-fade)">
  <path class="road-band" d="{band()}" filter="url(#road-soft)"></path>
  <path class="road-dash" d="{TRAIL_D}"></path>
</g>

<style>
  .road-band {{ fill: currentColor; opacity: 0.07; }}
  .road-dash {{ fill: none; stroke: var(--paper); stroke-width: 0.9; stroke-dasharray: 5 7; opacity: 0.8; }}
</style>
'''

if __name__ == '__main__':
    with open(sys.argv[1], 'w', encoding='utf-8') as fh:
        fh.write(astro)
    print('wrote', sys.argv[1], len(astro))
